import {
  copyFileSync,
  existsSync,
  lstatSync,
  mkdtempSync,
  rmSync,
  statSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { log } from "../../log.ts";

/**
 * Codex features that would give the model abilities of its own: a shell,
 * browsers, plugins, other agents, memory. Conduit uses Codex as a model, so
 * they are off. The user's own config.toml (MCP servers, plugins, profiles) is
 * not read at all because the process runs against a scratch CODEX_HOME.
 */
const CONFIG = `# Generated by conduit. Codex acts as a model here; the client owns every tool.
check_for_update_on_startup = false
cli_auth_credentials_store = "file"
web_search = "disabled"

[features]
shell_tool = false
unified_exec = false
apps = false
plugins = false
goals = false
multi_agent = false
multi_agent_v2 = false
browser_use = false
computer_use = false
image_generation = false
in_app_browser = false
hooks = false
memories = false
view_image = false
skill_search = false
tool_suggest = false
sleep_tool = false
web_search_cached = false
web_search_request = false
code_mode = false
code_mode_only = false
`;

/** Where Codex keeps its login for a given CODEX_HOME setting. */
export function codexHomeOf(configured: string | undefined): string {
  return configured ?? process.env.CODEX_HOME ?? path.join(os.homedir(), ".codex");
}

/**
 * A throwaway CODEX_HOME holding conduit's minimal config and a link to the
 * login, so a Codex process sees none of the user's own settings. Returns the
 * directory and a function that removes it.
 */
export function scratchCodexHome(configured: string | undefined): {
  dir: string;
  remove: () => void;
} {
  const source = codexHomeOf(configured);
  const dir = mkdtempSync(path.join(os.tmpdir(), "conduit-codex-"));
  writeFileSync(path.join(dir, "config.toml"), CONFIG, { mode: 0o600 });
  const from = path.join(source, "auth.json");
  const to = path.join(dir, "auth.json");
  try {
    if (existsSync(from)) {
      try {
        symlinkSync(from, to);
      } catch (error) {
        // Windows forbids symlinks without developer mode or elevation.
        if ((error as NodeJS.ErrnoException).code !== "EPERM") throw error;
        copyFileSync(from, to);
      }
    }
  } catch (error) {
    log.warn("could not link Codex credentials into the scratch home", { error: String(error) });
  }
  return {
    dir,
    remove: () => {
      // Refresh tokens rotate, so a refresh inside the scratch dir (which replaces the link
      // with a plain file) invalidates the one in the real home; carry the newer file back.
      try {
        if (!lstatSync(to).isSymbolicLink() && statSync(to).mtimeMs > statSync(from).mtimeMs) {
          copyFileSync(to, from);
        }
      } catch {}
      rmSync(dir, { recursive: true, force: true });
    },
  };
}
